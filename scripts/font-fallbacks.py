#!/usr/bin/env python3
"""
Metric-matched fallbacks for the shipped faces.

A web font that arrives after first paint replaces whatever fallback was used, and if the two have
different metrics the text reflows. No amount of care in the CSS prevents that; the fix is to make
the *fallback* measure like the real face, which `size-adjust` and the `*-override` properties can
do, and to point the font stack at that adjusted fallback instead of at a generic family.

What is computed, per face:

  size-adjust        the ratio of average advance widths, so a line of fallback text is as wide as
                     the same line in the real face;
  ascent-override    the real face's ascent as a percentage of the em, already scaled;
  descent-override   the same for the descent;
  line-gap-override  the same for the line gap.

The fallback's own metrics are the published ones for the family the stack names — Times New Roman
for the serif display faces and Arial for the sans — because those fonts are not present in this
container to measure. The *real* face is measured from the file that actually ships, which is the
half that matters: it is the one that changes when the subset is rebuilt.

Arabic faces are deliberately **not** given fallbacks. Their fallback in the stack is a system Arabic
face ("Noto Naskh Arabic", "Geeza Pro") that is neither present here nor published with usable
metrics, and inventing numbers would produce a fallback that is confidently wrong — worse than no
fallback, because it would look adjusted. The Arabic above-fold face instead uses
`font-display: block` (see scripts/fonts.py), which removes the swap rather than matching it.

Usage: python3 scripts/font-fallbacks.py
"""
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "public" / "fonts"
OUT = ROOT / "src" / "styles" / "font-fallbacks.css"

# Published metrics for the fallbacks the token stacks name. Units per em, ascent, descent, line gap,
# and the average advance width of the Latin lowercase alphabet as a fraction of the em.
FALLBACKS = {
    "serif": {"local": "Times New Roman", "upem": 2048, "ascent": 1825, "descent": -443, "gap": 87, "avg": 0.4477},
    "sans": {"local": "Arial", "upem": 2048, "ascent": 1854, "descent": -434, "gap": 67, "avg": 0.5117},
}

# The faces to adjust, and which fallback each one's stack names.
TARGETS = [
    {"file": "cormorantgaramond-latin-var.woff2", "family": "Cormorant Garamond Fallback", "fallback": "serif", "weight": "300 700"},
    {"file": "manrope-latin-var.woff2", "family": "Manrope Fallback", "fallback": "sans", "weight": "200 800"},
]

SAMPLE = "abcdefghijklmnopqrstuvwxyz"


def average_advance(font: TTFont) -> float:
    """Mean advance of the lowercase alphabet, as a fraction of the em."""
    upem = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    widths = [hmtx[cmap[ord(char)]][0] for char in SAMPLE if ord(char) in cmap]
    if not widths:
        raise SystemExit("no sample glyphs found")
    return (sum(widths) / len(widths)) / upem


def metrics(font: TTFont) -> tuple[float, float, float]:
    upem = font["head"].unitsPerEm
    os2 = font["OS/2"]
    hhea = font["hhea"]
    ascent = max(getattr(os2, "sTypoAscender", 0), hhea.ascent)
    descent = min(getattr(os2, "sTypoDescender", 0), hhea.descent)
    gap = getattr(os2, "sTypoLineGap", 0) or hhea.lineGap
    return ascent / upem, descent / upem, gap / upem


def main() -> int:
    blocks: list[str] = [
        "/*",
        " * Generated by scripts/font-fallbacks.py — do not edit by hand.",
        " *",
        " * Fallbacks whose metrics match the shipped faces, so a font that arrives late does not",
        " * reflow the text it replaces. See the script for how each number is derived, and for why",
        " * the Arabic faces are not included.",
        " */",
        "",
    ]
    for target in TARGETS:
        path = FONTS / target["file"]
        if not path.exists():
            print(f"  ! missing {path}")
            continue
        font = TTFont(path, fontNumber=0)
        advance = average_advance(font)
        ascent, descent, gap = metrics(font)
        fallback = FALLBACKS[target["fallback"]]

        # Scale so the fallback's average advance matches the real face's.
        size_adjust = advance / fallback["avg"]

        blocks.append("@font-face {")
        blocks.append(f'  font-family: "{target["family"]}";')
        blocks.append(f'  src: local("{fallback["local"]}");')
        blocks.append("  font-style: normal;")
        blocks.append(f"  font-weight: {target['weight']};")
        blocks.append(f"  size-adjust: {size_adjust * 100:.2f}%;")
        blocks.append(f"  ascent-override: {ascent / size_adjust * 100:.2f}%;")
        blocks.append(f"  descent-override: {abs(descent) / size_adjust * 100:.2f}%;")
        blocks.append(f"  line-gap-override: {max(gap, 0) / size_adjust * 100:.2f}%;")
        blocks.append("}")
        blocks.append("")
        print(f"  {target['family']}: size-adjust {size_adjust * 100:.2f}% "
              f"(advance {advance:.4f} vs {fallback['avg']})")

    OUT.write_text("\n".join(blocks))
    print(f"\nstylesheet: {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
